CREATE SCHEMA IF NOT EXISTS ab;
SET search_path TO ab;

CREATE TABLE AB_CLIENT (
  AB_CLIENT_ID        INT PRIMARY KEY,
  AB_NOM              VARCHAR(100),
  AB_PRENOM           VARCHAR(100),
  AB_DATE_NAISSANCE   DATE,
  AB_EMAIL            VARCHAR(150),
  AB_TELEPHONE        VARCHAR(20),
  AB_ADRESSE          VARCHAR(255),
  AB_CODE_POSTAL      VARCHAR(10),
  AB_NUM_FISCAL       VARCHAR(30),
  AB_DATE_CREATION    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  AB_STATUT_CLIENT    VARCHAR(20));

CREATE TABLE AB_CONTRAT (
  AB_POLICY_NUMBER    VARCHAR(30) PRIMARY KEY,
  AB_CLIENT_ID        INT,
  AB_TYPE_ASSURANCE   VARCHAR(50),
  AB_DATE_DEBUT       DATE,
  AB_DATE_FIN         DATE,
  AB_PRIME_ANNUELLE   NUMERIC(10,2),
  AB_STATUT_CONTRAT   VARCHAR(20),
  AB_AGENCE_ID        INT);

CREATE TABLE AB_SINISTRE (
  AB_CLAIM_ID         INT PRIMARY KEY,
  AB_POLICY_NUMBER    VARCHAR(30),
  AB_DATE_SINISTRE    TIMESTAMP,
  AB_MONTANT_ESTIME   NUMERIC(12,2),
  AB_STATUT_SINISTRE  VARCHAR(30),
  AB_DESCRIPTION      TEXT);

CREATE TABLE AB_PAIEMENT (
  AB_PAYMENT_ID       INT PRIMARY KEY,
  AB_POLICY_NUMBER    VARCHAR(30),
  AB_DATE_PAIEMENT    DATE,
  AB_MONTANT          NUMERIC(10,2),
  AB_MODE_PAIEMENT    VARCHAR(30));

