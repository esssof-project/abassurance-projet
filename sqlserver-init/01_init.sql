CREATE SCHEMA IF NOT EXISTS ap;
SET search_path TO ap;

CREATE TABLE AP_USERS (
  AP_USER_ID INT PRIMARY KEY, AP_FULL_NAME VARCHAR(200), AP_BIRTH_DATE VARCHAR(10),
  AP_MAIL_ADDRESS VARCHAR(150), AP_PHONE_NUMBER VARCHAR(25), AP_STREET_ADDRESS VARCHAR(255),
  AP_ZIP_CODE VARCHAR(10), AP_CREATED_AT TIMESTAMP, AP_CUSTOMER_STATUS VARCHAR(20), AP_LOYALTY_SCORE INT);
CREATE TABLE AP_CONTRACTS (
  AP_CONTRACT_REF VARCHAR(30) PRIMARY KEY, AP_USER_ID INT, AP_PRODUCT_CODE VARCHAR(50),
  AP_START_DATE TIMESTAMP, AP_END_DATE TIMESTAMP, AP_MONTHLY_PREMIUM NUMERIC(10,2),
  AP_CONTRACT_STATE VARCHAR(20), AP_BROKER_CODE VARCHAR(30));
CREATE TABLE AP_CLAIMS (
  AP_SINISTRE_NUM INT PRIMARY KEY, AP_CONTRACT_REF VARCHAR(30), AP_INCIDENT_DATE VARCHAR(19),
  AP_ESTIMATED_AMOUNT NUMERIC(12,2), AP_CLAIM_STATUS VARCHAR(30), AP_CLAIM_COMMENT TEXT,
  AP_FRAUD_SCORE NUMERIC(5,2));
CREATE TABLE AP_PAYMENTS (
  AP_PAYMENT_REF UUID PRIMARY KEY DEFAULT gen_random_uuid(), AP_CONTRACT_REF VARCHAR(30),
  AP_PAYMENT_DATETIME TIMESTAMP, AP_AMOUNT_PAID NUMERIC(10,2), AP_PAYMENT_CHANNEL VARCHAR(30),
  AP_TRANSACTION_STATUS VARCHAR(20));
